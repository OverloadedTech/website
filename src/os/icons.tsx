function paths(art: string) {
  let full = "";
  let half = "";
  art
    .trim()
    .split("\n")
    .forEach((row, y) =>
      [...row].forEach((c, x) => {
        const px = `M${x} ${y}h1v1h-1z`;
        if (c === "#") full += px;
        if (c === "o") half += px;
      }),
    );
  return { full, half };
}

const cache: Record<string, { full: string; half: string }> = {};

export function Icon({ name }: { name: string }) {
  const p = (cache[name] ??= paths(ART[name] ?? ART.file));
  return (
    <svg class="icon" viewBox="0 0 12 12" shape-rendering="crispEdges" aria-hidden="true">
      <path d={p.full} fill="currentColor" />
      <path d={p.half} fill="currentColor" opacity="0.4" />
    </svg>
  );
}
